import { describe, it, expect } from "vitest";
import { execFile } from "child_process";
import { promisify } from "util";
import { readFileSync } from "fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { runAdapterLoop } from "../../src/lib/agent-loop/loop";

const execFileAsync = promisify(execFile);

const CLI = ["servers/textkit/cli.js"];
const SERVER = "servers/textkit/mcp-server.js";

/**
 * The ONE documented hand adjustment to the generated dogfood server:
 * the generator emits a PATH binary name ("textkit"), but this bundled
 * copy must run the local cli.js via node. Everything else in the
 * committed file is byte-identical generator output — enforced by the
 * test below, so the dogfood claim is mechanical, not a promise.
 */
export function applyBundledAdjustment(generated: string): string {
  let out = generated;
  out = out.replace(
    " * Generated by FrankenMCP\n",
    " * Generated by FrankenMCP\n * HAND ADJUSTMENT: Changed CLI to run the local bundled cli.js via Node instead of spawning a PATH binary.\n",
  );
  out = out.replace(
    'import { promisify } from "util";\n',
    'import { promisify } from "util";\nimport { fileURLToPath } from "url";\nimport { dirname, resolve } from "path";\n',
  );
  out = out.replace(
    "const execFileAsync = promisify(execFile);\n",
    "const execFileAsync = promisify(execFile);\nconst __filename = fileURLToPath(import.meta.url);\nconst __dirname = dirname(__filename);\n",
  );
  out = out.replace(
    '// The real CLI binary this server wraps\nconst CLI = "textkit";',
    '// The real CLI binary: run the local cli.js via Node instead of PATH lookup\nconst CLI = process.execPath;\nconst CLI_ARGS = [resolve(__dirname, "cli.js")];',
  );
  out = out.replace("  const argv = [];", "  const argv = [...CLI_ARGS];");
  return out;
}

async function getHelpText(): Promise<string> {
  const { stdout } = await execFileAsync("node", [...CLI, "--help"]);
  return stdout;
}

async function runCli(args: string[]): Promise<string> {
  const { stdout } = await execFileAsync("node", [...CLI, ...args]);
  return stdout.trim();
}

function getTextContent(content: unknown): string {
  const arr = Array.isArray(content) ? content : [];
  return arr
    .filter((part): part is { type: "text"; text: string } => {
      return (
        typeof part === "object" &&
        part !== null &&
        (part as { type?: unknown }).type === "text" &&
        typeof (part as { text?: unknown }).text === "string"
      );
    })
    .map((part) => part.text)
    .join("");
}

describe("textkit dogfood (generated server)", () => {
  it("agent loop generates 4 verified tools from textkit --help", async () => {
    const result = runAdapterLoop(await getHelpText());
    expect(result.summary.verified).toBe(true);
    expect(result.summary.toolsGenerated).toEqual(4);
    expect(result.tools.map((t) => t.name).sort()).toEqual(["reverse", "slugify", "upper", "wc"]);
  });

  it("committed server is byte-identical to fresh generation + the one adjustment", async () => {
    const result = runAdapterLoop(await getHelpText());
    const expected = applyBundledAdjustment(result.files["server.js"]);
    const committed = readFileSync(SERVER, "utf-8");
    expect(committed).toBe(expected);
  });

  it("committed server answers live MCP calls with the CLI's own outputs", async () => {
    const transport = new StdioClientTransport({
      command: "node",
      args: [SERVER],
    });
    const client = new Client({ name: "dogfood-check", version: "1.0.0" }, { capabilities: {} });
    try {
      await client.connect(transport);

      const listed = await client.listTools();
      expect(listed.tools.map((t) => t.name).sort()).toEqual(["reverse", "slugify", "upper", "wc"]);

      const cases: Array<{
        tool: string;
        callArgs: Record<string, unknown>;
        cliArgs: string[];
      }> = [
        {
          tool: "wc",
          callArgs: { words: true, args: ["hello world"] },
          cliArgs: ["wc", "hello world", "--words"],
        },
        {
          tool: "reverse",
          callArgs: { upper: true, args: ["abc"] },
          cliArgs: ["reverse", "abc", "--upper"],
        },
        {
          tool: "slugify",
          callArgs: { separator: "_", args: ["Hello World!"] },
          cliArgs: ["slugify", "Hello World!", "--separator", "_"],
        },
        { tool: "upper", callArgs: { args: ["abc"] }, cliArgs: ["upper", "abc"] },
      ];
      for (const c of cases) {
        const res = await client.callTool({ name: c.tool, arguments: c.callArgs });
        expect(res.isError).toBeFalsy();
        expect(getTextContent(res.content).trim()).toBe(await runCli(c.cliArgs));
      }
    } finally {
      await client.close();
    }
  });
});
